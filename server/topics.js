// What lesson sentences can be about. Two kinds:
// - topic: what the sentence talks about ("Погода", "Собеседование"); the model gets the Russian name.
// - grammar: the structure or word area translating it practises ("Present Perfect", "Фразовые глаголы"); the
//   model gets `focus`, in English.
// `level` is the lowest level the topic makes sense at: it can't be picked for an easier lesson, and a sentence on
// it is written at that level or higher. Ids are stored in the learner's settings, so keep them when renaming.

const topic = (id, name, level) => ({ id, name, level });
const grammar = (id, name, level, focus) => ({ id, name, level, focus });

